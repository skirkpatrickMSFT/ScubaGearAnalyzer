import { test } from 'node:test';
import assert from 'node:assert/strict';

import {
  ALL_BASELINE_CONTROLS,
  CONTROLS_BY_PRODUCT,
  BASELINE_PRODUCTS,
  PRODUCT_ALIASES,
  SCUBAGEAR_BASELINE_VERSION,
  canonicalizeProduct,
  getControlById,
  getControlsByProduct,
  getControlsBySection,
  getSectionName,
  searchControls,
} from '../dist/src/shared/baseline-data.js';

import {
  extractProduct,
  detectAndParse,
  computeSummary,
  SCUBAGEAR_CURRENT_VERSION,
} from '../dist/src/shared/scubagear-parser.js';

test('baseline data is populated and internally consistent', () => {
  assert.ok(ALL_BASELINE_CONTROLS.length > 100, 'expected a substantial control set');

  const ids = ALL_BASELINE_CONTROLS.map((c) => c.id);
  assert.equal(new Set(ids).size, ids.length, 'control IDs must be unique');

  for (const c of ALL_BASELINE_CONTROLS) {
    assert.match(c.id, /^MS\.[A-Z0-9]+\.\d+\.\d+v\d+$/, `malformed id: ${c.id}`);
    assert.ok(c.title.length > 0, `${c.id} missing title`);
    assert.ok(c.rationale.length > 0, `${c.id} missing rationale`);
    assert.ok(['SHALL', 'SHALL NOT', 'SHOULD', 'SHOULD NOT'].includes(c.criticality));
    assert.ok(['Automated', 'Manual'].includes(c.checkType));
    assert.equal(c.product, c.id.split('.')[1]);
  }
});

test('v2.0.0 baseline changes are present', () => {
  // New or re-versioned in 2.0.0.
  for (const id of ['MS.AAD.3.2v2', 'MS.AAD.3.5v2', 'MS.EXO.2.2v3', 'MS.SHAREPOINT.3.3v2',
                    'MS.AAD.9.1v1', 'MS.SECURITYSUITE.1.1v1', 'MS.SECURITYSUITE.6.2v1']) {
    assert.ok(ALL_BASELINE_CONTROLS.some((c) => c.id === id), `${id} should exist`);
  }
  // Removed or superseded in 2.0.0 (Defender retired into Security Suite).
  for (const id of ['MS.DEFENDER.1.1v1', 'MS.DEFENDER.4.1v2', 'MS.EXO.8.1v2', 'MS.EXO.14.1v2',
                    'MS.AAD.3.2v1', 'MS.AAD.3.5v1', 'MS.EXO.2.2v2', 'MS.SHAREPOINT.3.3v1']) {
    assert.ok(!ALL_BASELINE_CONTROLS.some((c) => c.id === id), `${id} should be gone`);
  }
});

test('baseline text is free of upstream badge markup', () => {
  for (const c of ALL_BASELINE_CONTROLS) {
    assert.ok(!/shields\.io|!\[/.test(`${c.title} ${c.description}`), `${c.id} leaks badge markup`);
  }
});

test('indicator badges drive BOD 25-01, check type and configuration flags', () => {
  const bod = getControlById('MS.SECURITYSUITE.4.1v1');
  assert.equal(bod.bod2501, true, 'badge placed after the policy marker must still count');
  assert.equal(bod.checkType, 'Automated');

  const cfg = getControlById('MS.SECURITYSUITE.2.1v1');
  assert.equal(cfg.bod2501, false);
  assert.equal(cfg.requiresConfiguration, true);
  assert.equal(cfg.configurable, true);

  assert.ok(ALL_BASELINE_CONTROLS.some((c) => c.checkType === 'Manual'), 'Manual badge should be honoured');
});

test('exclusionType is captured from upstream markers', () => {
  const withExclusion = ALL_BASELINE_CONTROLS.filter((c) => c.exclusionType);
  assert.ok(withExclusion.length > 0);
  assert.equal(getControlById('MS.SECURITYSUITE.2.1v1').exclusionType, 'SensitiveUsers');
});

test('getControlById tolerates version drift', () => {
  // A report generated by an older ScubaGear still resolves to the current control.
  const c = getControlById('MS.AAD.3.2v1');
  assert.ok(c, 'should fall back across version suffixes');
  assert.equal(c.id, 'MS.AAD.3.2v2');
});

test('sections are resolved per product, not globally', () => {
  assert.equal(getSectionName(1, 'AAD'), 'Legacy Authentication');
  assert.equal(getSectionName(1, 'TEAMS'), 'Meeting Policies');
  assert.equal(getSectionName(1, 'SECURITYSUITE'), 'Malware Protection');
  assert.equal(getSectionName(1, 'DEFENDER'), 'Malware Protection', 'legacy key resolves to its replacement');

  const ss3 = getControlsBySection(3, 'SECURITYSUITE');
  assert.ok(ss3.length > 0, 'Security Suite section 3 should return controls');
});

test('product registry covers every shipped product', () => {
  assert.ok(BASELINE_PRODUCTS.includes('AAD'));
  assert.ok(BASELINE_PRODUCTS.includes('POWERBI'), 'Power BI should be generated');
  for (const p of BASELINE_PRODUCTS) {
    assert.ok(CONTROLS_BY_PRODUCT[p].length > 0, `${p} has no controls`);
    assert.deepEqual(getControlsByProduct(p), CONTROLS_BY_PRODUCT[p]);
  }
});

test('bundled version matches the parser version', () => {
  assert.equal(SCUBAGEAR_CURRENT_VERSION, SCUBAGEAR_BASELINE_VERSION);
});

test('search finds controls by keyword', () => {
  const hits = searchControls('legacy authentication');
  assert.ok(hits.length > 0);
});

// ── ScubaGear 2.0 renamed DEFENDER -> SECURITYSUITE ──

test('legacy product keys resolve through the alias registry', () => {
  // The pinned baseline ships SECURITYSUITE, so v1.x DEFENDER results must fold onto it.
  assert.equal(PRODUCT_ALIASES.DEFENDER, 'SECURITYSUITE');
  assert.equal(canonicalizeProduct('DEFENDER'), 'SECURITYSUITE');
  assert.equal(canonicalizeProduct('defender'), 'SECURITYSUITE');
  assert.equal(canonicalizeProduct('SECURITYSUITE'), 'SECURITYSUITE');
});

test('policy IDs using the legacy product still resolve', () => {
  assert.equal(extractProduct('MS.SECURITYSUITE.1.1v1'), 'SECURITYSUITE');
  assert.equal(extractProduct('MS.DEFENDER.1.1v1'), 'SECURITYSUITE');
});

test('ScubaResults using a legacy product key parses', () => {
  const results = {
    Results: {
      Defender: [
        {
          GroupName: 'Preset Security Profiles',
          GroupNumber: 1,
          Controls: [
            {
              'Control ID': 'MS.DEFENDER.1.1v1',
              Requirement: 'Standard and strict preset security policies SHALL be enabled.',
              Result: 'Fail',
              Criticality: 'SHALL',
              Details: 'Requirement not met',
            },
          ],
        },
      ],
    },
  };

  const { controls, format } = detectAndParse(results);
  assert.equal(format, 'ScubaResults');
  assert.equal(controls.length, 1);
  assert.equal(controls[0].product, 'SECURITYSUITE', 'legacy key folds onto the canonical product');
  assert.equal(controls[0].status, 'Fail');
});

test('summary tolerates products absent from the bundled baselines', () => {
  const results = {
    Results: {
      SomeFutureProduct: [
        {
          Controls: [
            {
              'Control ID': 'MS.FUTUREPRODUCT.1.1v1',
              Result: 'Pass',
              Criticality: 'SHALL',
              Details: 'ok',
            },
          ],
        },
      ],
    },
  };

  const { controls } = detectAndParse(results);
  assert.equal(controls.length, 1, 'unknown products must not be dropped');
  assert.equal(controls[0].product, 'FUTUREPRODUCT');

  const summary = computeSummary(controls);
  assert.equal(summary.total, 1);
  assert.equal(summary.pass, 1);
});

test('legacy TestResults array format still parses', () => {
  const raw = [
    {
      ActualValue: { enabled: false },
      Commandlet: ['Get-Thing'],
      Criticality: 'SHALL',
      PolicyId: 'MS.AAD.1.1v1',
      ReportDetails: 'Requirement not met',
      RequirementMet: false,
    },
  ];
  const { controls, format } = detectAndParse(raw);
  assert.equal(format, 'TestResults');
  assert.equal(controls[0].product, 'AAD');
  assert.equal(controls[0].status, 'Fail');
  assert.ok(controls[0].actualValue.includes('enabled'));
});
